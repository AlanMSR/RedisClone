constexpr size_t headerBytes = 4;

struct Conn {
    int fd = -1;

    // applications intention for the event loop
    bool want_read = false;
    bool want_write = false;
    bool want_close = false;

    // buffer input output
    std::vector<uint8_t> incoming; // data to be parse with the application
    std::vector<uint8_t> outgoing; // responses generated by the application
};

static void handle_read(Conn* conn);
static void handle_write(Conn* conn);
static Conn* handle_accept(int fd);
static void buf_append(std::vector<uint8_t> &buf, const uint8_t* data, size_t len);
static void buf_consume(std::vector<uint8_t> &buf, size_t n);
static bool try_one_request(Conn* conn);
static void fd_set_nonblocking(int fd);
// static size_t one_request(int connFd);

// server
int main() {
    int socketFD = socket(AF_INET, SOCK_STREAM, 0);

    int val = 1;
    setsockopt(socketFD, SOL_SOCKET, SO_REUSEADDR, &val, sizeof(val));

    struct sockaddr_in addr = {};
    addr.sin_family = AF_INET;
    addr.sin_port = ntohs(1234);
    addr.sin_addr.s_addr = ntohl(0);

    int bindResult = bind(socketFD, (const struct sockaddr*)&addr, sizeof(addr));
    if (bindResult)
        die("bind()");

    fd_set_nonblocking(socketFD);

    bindResult = listen(socketFD, SOMAXCONN);

    if (bindResult)
        die("listen()");

    // a map of all clients connections, keyed by their file descriptor
    std::vector<Conn*> fd2conn;

    std::vector<struct pollfd> poll_args;
    // event loop
    while (true) {
        // prepare arguments for call
        poll_args.clear();
        // listening sockets in the first position
        struct pollfd pfd = {socketFD, POLLIN, 0};
        poll_args.push_back(pfd);

        // connection sockets
        for (Conn* conn : fd2conn) {
            if (!conn)
                continue;

            struct pollfd pfd = {conn->fd, POLLERR, 0};
            if (conn->want_read)
                pfd.events |= POLLIN;
            
            if (conn->want_write)
                pfd.events |= POLLOUT;

            poll_args.push_back(pfd);
        }

        // wait for readiness
        int rv = poll(poll_args.data(), (nfds_t)poll_args.size(), -1);
        if (rv < 0 && errno == EINTR)
            continue; // not an error, you should just try again

        if (rv < 0)
            die("poll()");
        printf("HEREEEEEEEEEEEEEEEEEEEEEEEEEEEEEEEEEEEEEEEEEEEEEEEEEEEE");
        // handling listening sockets
        if (poll_args[0].revents) {
            if (Conn* conn = handle_accept(socketFD)) {
                // put it in map
                if (fd2conn.size() <= (size_t)conn->fd)
                    fd2conn.resize(conn->fd + 1);

                fd2conn[conn->fd] = conn;
            }
        }
        
        // handle connection sockets
        for (size_t i = 1; i < poll_args.size(); ++i) { // skiping 1st, which is the listening socket
            uint32_t ready = poll_args[i].revents;
            Conn* conn = fd2conn[poll_args[i].fd];
            
            if (ready & POLLIN)
                handle_read(conn);

            if (ready & POLLOUT)
                handle_write(conn);
            
            // close connection if requested or on error
            if ((ready & POLLERR) || conn->want_close) {
                (void)close(conn->fd);
                fd2conn[conn->fd] = NULL;
                delete conn;
            }
        }
    }

    return 0;
}

static void fd_set_nonblocking(int fd) {
    fcntl(fd, F_SETFL, fcntl(fd, F_GETFL, 0) | O_NONBLOCK);
}

static Conn* handle_accept(int fd) {
    // accept
    struct sockaddr_in client_addr = {};
    socklen_t addrlen = sizeof(client_addr);
    int connfd = accept(fd, (struct sockaddr*)&client_addr, &addrlen);
    if (connfd < 0) {
        return NULL;
    }
    uint32_t ip = client_addr.sin_addr.s_addr;
    fprintf(stderr, "new client from %u.%u.%u.%u:%u\n",
        ip & 255, (ip >> 8) & 255, (ip >> 16) & 255, ip >> 24,
        ntohs(client_addr.sin_port)
    );

    // set the new connection to non-blocking
    fd_set_nonblocking(connfd);

    Conn* conn = new Conn();
    conn->fd = connfd;
    conn->want_read = true;
    
    return conn;
}

static void handle_read(Conn* conn) {
    // do a non blocking read
    uint8_t buf[64 * 1024];
    ssize_t rv = read(conn->fd, buf, sizeof(buf));
    if (rv < 0) {
        conn->want_close = true;
        return;
    }
    if (rv == 0) {
        conn->want_close = true; // EOF, the client closed the connection
        return;
    }

    // add new data to Conn::incoming buffer
    buf_append(conn->incoming, buf, (size_t)rv);

    // try to parse the accumulated data in the buffer
    // process parsed message
    // remove message from conn::incoming buffer
    while (try_one_request(conn)) {}

    if (!conn->outgoing.empty()) {
        conn->want_write = true;
        conn->want_read = false;
    }
}

static void handle_write(Conn* conn) {
    assert(!conn->outgoing.empty());

    ssize_t rv = write(conn->fd, conn->outgoing.data(), conn->outgoing.size());
    if (rv < 0 && errno == EAGAIN) {
        return; // not ready
    }
    if (rv < 0) {
        conn->want_close = true;
        return;
    }

    // remove the sent data from Conn::outgoing buffer
    buf_consume(conn->outgoing, (size_t)rv);

    // switch state, readiness intention
    if (conn->outgoing.empty()) {
        conn->want_write = false;
        conn->want_read = true;
    }
}

// append to the back
static void buf_append(std::vector<uint8_t> &buf, const uint8_t* data, size_t len) {
    buf.insert(buf.end(), data, data + len);
}

// remove from the front
static void buf_consume(std::vector<uint8_t> &buf, size_t n) {
    buf.erase(buf.begin(), buf.begin() + n);
}

static bool try_one_request(Conn* conn) {
    // try to parse accumulated buffer
    // protocol message header is 4 bytes, which is the length of the message body
    if (conn->incoming.size() < headerBytes)
        return false; // not enough data yet

    uint32_t len = 0;
    memcpy(&len, conn->incoming.data(), headerBytes);
    if (len > k_max_msg) {
        conn->want_close = true;
        return false;
    }

    //protocol: message body
    if (headerBytes + len > conn->incoming.size())
        return false; // not enough data yet

    const uint8_t* request = &conn->incoming[headerBytes];

    // proccess parsed message
    printf("client says: len:%d data:%.*s\n",
        len, len < 100 ? len : 100, request);

    // generate the response
    buf_append(conn->outgoing, (const uint8_t*)&len, headerBytes);
    buf_append(conn->outgoing, request, len);

    // remove the processed message from Conn::incoming
    buf_consume(conn->incoming, headerBytes + len);

    return true; // all went good
}
