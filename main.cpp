constexpr size_t headerBytes = 4;

static struct {
    HMap db;
} g_data;

// KV pair
struct Entry {
    struct HNode node;
    std::string key;
    std::string val;
};

enum {
    RES_OK = 0,
    RES_ERR = 1,    // error
    RES_NX = 2,     // key not found
};

struct Conn {
    int fd = -1;

    // applications intention for the event loop
    bool want_read = false;
    bool want_write = false;
    bool want_close = false;

    // buffer input output
    Buffer incoming{4096}; // data to be parse with the application
    Buffer outgoing{4096}; // responses generated by the application
};

struct Response {
    uint32_t status = 0;
    std::vector<uint8_t> data;
};

static void handle_read(Conn* conn);
static void handle_write(Conn* conn);
static Conn* handle_accept(int fd);
static bool try_one_request(Conn* conn);
static void fd_set_nonblocking(int fd);
static bool read_uint32(const uint8_t*& cur, const uint8_t* end, uint32_t& out);
static bool read_str(const uint8_t*& cur, const uint8_t* end, size_t n, std::string& out);
static int32_t parse_req(const uint8_t* data, size_t size, std::vector<std::string>& out);
static void do_request(std::vector<std::string>& cmd, Response& out);
static void make_response(const Response& resp, Buffer& out);

static bool entry_eq(HNode* lhs, HNode* rhs);
static void do_get(std::vector<std::string>& cmd, Response& out);
static void do_set(std::vector<std::string>& cmd, Response& out);
