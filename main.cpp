static void do_keys(std::vector<std::string>& cmd, Buffer& out) {
    out_arr(out, (uint32_t)hm_size(&g_data.db));
    hm_foreach(&g_data.db, &cb_keys, (void*)&out);
}

static void do_get(std::vector<std::string>& cmd, Buffer& out) {
    Entry key;
    key.key.swap(cmd[1]);
    key.node.hcode = str_hash((uint8_t*)key.key.data(), key.key.size());
    // lookup
    HNode* node = hm_lookup(&g_data.db, &key.node, &entry_eq);
    if (!node) {
        return out_nil(out);
    }

    // copy value
    const std::string &val = container_of(node, Entry, node)->val;
    return out_str(out, val.data(), val.size());
}

static void do_set(std::vector<std::string>& cmd, Buffer& out) {
    Entry key;
    key.key.swap(cmd[1]);
    key.node.hcode = str_hash((uint8_t*)key.key.data(), key.key.size());

    HNode* node = hm_lookup(&g_data.db, &key.node, &entry_eq);
    if (node) {
        container_of(node, Entry, node)->val.swap(cmd[2]);
    } else {
        Entry* newEnt = new Entry();
        newEnt->key.swap(key.key);
        newEnt->val.swap(cmd[2]);
        newEnt->node.hcode = key.node.hcode; // not computing hcode again
        hm_insert(&g_data.db, &newEnt->node);
    }

    return out_nil(out);
}

static void do_del(std::vector<std::string>& cmd, Buffer& out) {
    Entry key;
    key.key.swap(cmd[1]);
    key.node.hcode = str_hash((uint8_t*)key.key.data(), key.key.size());
    HNode* node = hm_delete(&g_data.db, &key.node, &entry_eq);
    if (!node) {
        return out_int(out, 0);
    }

    delete container_of(node, Entry, node);
    return out_int(out, node ? 1 : 0);
}

static void do_zquery(std::vector<std::string>& cmd, Buffer& out) {
    double score = 0;
    if (!str2dbl(cmd[2], score))
        return out_err(out, ERR_BAD_ARG, "expected fp number");
    
    const std::string &name = cmd[3];
    int64_t offset = 0, limit = 0;
    if (!str2int(cmd[4], offset) || !str2int(cmd[5], limit))
        return out_err(out, ERR_BAD_ARG, "expect int");

    ZSet* zset = expect_zset(cmd[1]);
    if (!zset)
        return out_err(out, ERR_BAD_TYP, "expected zset");
    
    // seek key
    if (limit <= 0) {
        return out_arr(out, 0);
    }
    ZNode* znode = zset_seekge(zset, score, name.data(), name.size());

    znode = znode_offset(znode, offset);

    size_t ctx = out_begin_arr(out);
    int64_t n = 0;
    while(znode && n < limit) {
        out_str(out, znode->name, znode->len);
        out_dbl(out, znode->score);
        znode = znode_offset(znode, 1);
        n += 2;
    }
    out_end_arr(out, ctx, (uint32_t)n);
}

// zadd key score value
static void do_zadd(std::vector<std::string>& cmd, Buffer& out) {
    double score = 0;
    if (!str2dbl(cmd[2], score))
        return out_err(out, ERR_BAD_ARG, "expect double");

    Entry key;
    key.key.swap(cmd[1]);
    key.node.hcode = str_hash((uint8_t*)key.key.data(), key.key.size());
    HNode* hnode = hm_lookup(&g_data.db, &key.node, &entry_eq);

    Entry* ent = nullptr;
    if (!hnode) {
        ent = new Entry();
        ent->key.swap(key.key);
        ent->node.hcode = key.node.hcode;
        ent->type = T_ZSET;
        hm_insert(&g_data.db, &ent->node);
    } else {
        ent = container_of(hnode, Entry, node);
        if (ent->type != T_ZSET)
            return out_err(out, ERR_BAD_TYP, "Expected zset");
    }

    const std::string &name = cmd[3];
    bool rv = zset_insert(&ent->zset, name.data(), name.length(), score);
    return out_int(out, (int64_t)rv);
}

// zrem key value
static void do_zrem(std::vector<std::string>& cmd, Buffer& out) {
    ZSet* zset = expect_zset(cmd[1]);
    if (!zset)
        return out_err(out, ERR_BAD_TYP, "expected zset");
    
    const std::string &name = cmd[2];
    ZNode* znode = zset_lookup(zset, name.data(), name.length());

    if (!znode)
        return out_int(out, 0);
    
    zset_delete(zset, znode);
    return out_int(out, 1);
}

// zscore key name
static void do_zscore(std::vector<std::string>& cmd, Buffer& out) {
    ZSet* zset = expect_zset(cmd[1]);
    if (!zset)
        return out_err(out, ERR_BAD_TYP, "expected zset");

    const std::string &name = cmd[2];
    ZNode* znode = zset_lookup(zset, name.data(), name.length());
    if (!znode)
        return out_nil(out);

    return out_dbl(out, znode->score);
}

static void do_expire(std::vector<std::string> &cmd, Buffer &out) {
    int64_t ttl_ms = 0;
    if (!str2int(cmd[2], ttl_ms))
        return out_err(out, ERR_BAD_ARG, "expect int64");
    
    LookupKey key;
    key.key.swap(cmd[1]);
    key.node.hcode = str_hash((uint8_t *)key.key.data(), key.key.size());
    HNode* node = hm_lookup(&g_data.db, &key.node, &entry_eq);
    // set ttl
    if (node) {
        Entry* ent = container_of(node, Entry, node);
        entry_set_ttl(ent, ttl_ms);
    }

    return out_int(out, node ? 1 : 0);
}

static void do_persist(std::vector<std::string> &cmd, Buffer &out) {
    LookupKey key;
    key.key.swap(cmd[1]);
    key.node.hcode = str_hash((uint8_t *)key.key.data(), key.key.size());
    HNode* node = hm_lookup(&g_data.db, &key.node, &entry_eq);
    if (!node)
        return out_int(out, 0);

    Entry* ent = container_of(node, Entry, node);
    if (ent->heap_idx == (size_t)-1)
        return out_int(out, 0); // not ttl

    entry_set_ttl(ent, -1);
    return out_int(out, 1);
}

// ============================================================
// Command dispatcher
// ============================================================

static void do_request(std::vector<std::string>& cmd, Buffer& out) {
    if (cmd.size() == 2 && cmd[0] == "get")         { return do_get(cmd, out); }
    else if (cmd.size() == 3 && cmd[0] == "set")    { return do_set(cmd, out); }
    else if (cmd.size() == 2 && cmd[0] == "del")    { return do_del(cmd, out); }
    else if (cmd.size() == 1 && cmd[0] == "keys")   { return do_keys(cmd, out); }
    else if (cmd.size() == 6 && cmd[0] == "zquery") { return do_zquery(cmd, out); }
    else if (cmd.size() == 4 && cmd[0] == "zadd")   { return do_zadd(cmd, out); }
    else if (cmd.size() == 3 && cmd[0] == "zrem")   { return do_zrem(cmd, out); }
    else if (cmd.size() == 3 && cmd[0] == "zscore") { return do_zscore(cmd, out); }
    else if (cmd.size() == 3 && cmd[0] == "expire") { return do_expire(cmd, out); }
    else if (cmd.size() == 2 && cmd[0] == "persist") { return do_persist(cmd, out); }
    else { out_err(out, ERR_UNKNOWN, "unrecognized command"); } // unrecognized command
}