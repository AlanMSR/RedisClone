// server
int main() {
    int socketFD = socket(AF_INET, SOCK_STREAM, 0);

    int val = 1;
    setsockopt(socketFD, SOL_SOCKET, SO_REUSEADDR, &val, sizeof(val));

    struct sockaddr_in addr = {};
    addr.sin_family = AF_INET;
    addr.sin_port = ntohs(1234);
    addr.sin_addr.s_addr = ntohl(0);

    int bindResult = bind(socketFD, (const struct sockaddr*)&addr, sizeof(addr));
    if (bindResult)
        die("bind()");

    fd_set_nonblocking(socketFD);

    bindResult = listen(socketFD, SOMAXCONN);

    if (bindResult)
        die("listen()");

    dlist_init(&g_data.idle_list);

    std::vector<struct pollfd> poll_args;
    // event loop
    while (true) {
        // prepare arguments for call
        poll_args.clear();
        // listening sockets in the first position
        struct pollfd pfd = {socketFD, POLLIN, 0};
        poll_args.push_back(pfd);

        // connection sockets
        for (Conn* conn : g_data.fd2conn) {
            if (!conn)
                continue;

            struct pollfd pfd = {conn->fd, POLLERR, 0};
            if (conn->want_read)
                pfd.events |= POLLIN;
            
            if (conn->want_write)
                pfd.events |= POLLOUT;

            poll_args.push_back(pfd);
        }

        // wait for readiness
         int32_t timeout_ms = next_timer_ms();
        int rv = poll(poll_args.data(), (nfds_t)poll_args.size(), timeout_ms);
        if (rv < 0 && errno == EINTR)
            continue; // not an error, you should just try again

        if (rv < 0)
            die("poll()");

        // handling listening sockets
        if (poll_args[0].revents)
            handle_accept(socketFD);
        
        // handle connection sockets
        for (size_t i = 1; i < poll_args.size(); ++i) { // skiping 1st, which is the listening socket
            uint32_t ready = poll_args[i].revents;
            // Conn* conn = fd2conn[poll_args[i].fd];
            if (ready == 0)
                continue;

            Conn* conn = g_data.fd2conn[poll_args[i].fd];
            conn->last_active_ms = get_monotonic_msec(); 

            // updating timer moving it to the end of the list
            conn->last_active_ms = get_monotonic_msec();
            dlist_detach(&conn->idle_node);
            dlist_insert_before(&g_data.idle_list, &conn->idle_node);
            
            if (ready & POLLIN)
                handle_read(conn);

            if (ready & POLLOUT)
                handle_write(conn);
            
            // close connection if requested or on error
            if ((ready & POLLERR) || conn->want_close) {
                conn_destroy(conn);
            }
        }
        process_timers();
    }

    return 0;
}

static uint64_t get_monotonic_msec() {
    struct timespec tv = {0, 0};
    clock_gettime(CLOCK_MONOTONIC, &tv);
    return uint64_t(tv.tv_sec) * 1000 + tv.tv_nsec / 1000 / 1000;
}

static int32_t next_timer_ms() {
    uint64_t now_ms = get_monotonic_msec();
    uint64_t next_ms = (uint64_t)-1; // maxim value

    if (!dlist_empty(&g_data.idle_list)) {
        Conn* conn = container_of(g_data.idle_list.next, Conn, idle_node);
        next_ms = conn->last_active_ms + k_idle_timeout_ms;
    }
    // ttl using a heap
    if (!g_data.heap.empty() && g_data.heap[0].val < next_ms) {
        next_ms = g_data.heap[0].val;
    }
    // timeout
    if (next_ms == (uint64_t)-1 ) {
        return -1; // no timer
    }
    if (next_ms <= now_ms) {
        return 0;
    }
    
    return (int32_t) (next_ms - now_ms);
}

static void process_timers() {
    uint64_t now_ms = get_monotonic_msec();
    while (!dlist_empty(&g_data.idle_list)) {
        Conn* conn = container_of(g_data.idle_list.next, Conn, idle_node);
        uint64_t next_ms = conn->last_active_ms + k_idle_timeout_ms;
        if (next_ms >= now_ms)
            break; //not expired
        
        fprintf(stderr, "removing idle connection: %d\n", conn->fd);
        conn_destroy(conn);
    }
    // ttl timers using heap
    const std::vector<HeapItem>& heap = g_data.heap;
    const size_t k_max_works = 2000;
    size_t nworks = 0;
    while (!heap.empty() && heap[0].val < now_ms && nworks++ < k_max_works) {
        Entry* ent = container_of(heap[0].ref, Entry, heap_idx);
        hm_delete(&g_data.db, &ent->node, &hnode_same);
        entry_del(ent);
    }
}

