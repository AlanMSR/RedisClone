static void heap_upsert(std::vector<HeapItem>& arr, size_t pos, HeapItem t) {
    if (pos < arr.size()) {
        arr[pos] = t;
    } else {
        pos = arr.size();
        arr.push_back(t);
    }
    heap_update(arr.data(), pos, arr.size());
}

